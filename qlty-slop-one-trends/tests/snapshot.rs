/// Three weekly commits: June 25, July 2, and July 9, 2025.
fn weekly_repo() -> (TestRepo, Vec<String>) {
    let repo = TestRepo::new();
    repo.write("src/a.ts", "export const a = 1;\n");
    let first = repo.commit("2025-06-25T12:00:00-04:00");
    repo.write("src/a.ts", "export const a = 2;\n");
    repo.write("src/b.ts", "export const b = 1;\n");
    let second = repo.commit("2025-07-02T12:00:00-04:00");
    repo.write("src/b.ts", "export const b = 2;\n");
    let third = repo.commit("2025-07-09T12:00:00-04:00");
    (repo, vec![first, second, third])
}

fn freeze_weekly(repo: &TestRepo) -> Manifest {
    let options = repo.options("2025-07-01", Interval::Week, AS_OF);
    freeze(&repo.run_dir("weekly"), &options).unwrap()
}

/// One commit in the week of July 7, 2025, holding `files`, frozen weekly.
fn freeze_files(repo: &TestRepo, files: &[(&str, &str)]) -> Manifest {
    for (path, contents) in files {
        repo.write(path, contents);
    }
    repo.commit("2025-07-02T12:00:00-04:00");
    repo.commit("2025-07-09T12:00:00-04:00");
    freeze_weekly(repo)
}

fn file_paths(snapshot: &Snapshot) -> Vec<&str> {
    snapshot
        .files
        .iter()
        .map(|entry| entry.path.as_str())
        .collect()
}

fn excluded_paths(snapshot: &Snapshot) -> Vec<&str> {
    snapshot
        .source_excluded
        .iter()
        .map(|entry| entry.path.as_str())
        .collect()
}

