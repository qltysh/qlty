/// The Interface profile rules that the frozen slopdetect runs applied and
/// that decision 3 drops, as `fnmatchcase` patterns.
const INTERFACE_PROFILE_PATTERNS: [&str; 6] = [
    "public/workers/**",
    "public/faiss/**",
    "vector_db/public/faiss/**",
    "playwright/**",
    "jest.config.*",
    "jest.setup.*",
];

struct ParityFixture {
    frozen: Manifest,
    frozen_root: PathBuf,
    interface: PathBuf,
}

/// The slopdetect checkout and the Interface repository, when both are
/// available.
fn parity_fixture(run_name: &str) -> Option<ParityFixture> {
    let slopdetect = PathBuf::from(env::var_os("SLOPDETECT_DIR")?);
    let interface = PathBuf::from(env::var_os("INTERFACE_REPO")?);
    let frozen_root = slopdetect.join(".ai/local").join(run_name);
    let frozen = RunDir::new(&frozen_root).load_manifest().ok()?;
    Some(ParityFixture {
        frozen,
        frozen_root,
        interface,
    })
}

fn fnmatch(pattern: &str) -> Regex {
    let mut expression = String::from("^");
    for c in pattern.chars() {
        match c {
            '*' => expression.push_str(".*"),
            '?' => expression.push('.'),
            other => expression.push_str(&regex::escape(&other.to_string())),
        }
    }
    expression.push('$');
    Regex::new(&expression).unwrap()
}

fn profile_matched(path: &str) -> bool {
    INTERFACE_PROFILE_PATTERNS
        .iter()
        .any(|pattern| fnmatch(pattern).is_match(path))
}

fn normalize_error(error: Option<&str>, root: &Path) -> Option<String> {
    error.map(|text| text.replace(&root.to_string_lossy().into_owned(), "<run>"))
}

fn assert_interface_parity(run_name: &str, interval: Interval) {
    let Some(fixture) = parity_fixture(run_name) else {
        eprintln!("skipping {run_name}: set SLOPDETECT_DIR and INTERFACE_REPO");
        return;
    };
    let scratch = tempfile::tempdir().unwrap();
    let run = RunDir::new(scratch.path().join(run_name));
    let options = FreezeOptions {
        repo: fixture.interface.clone(),
        since: fixture.frozen.since.parse().unwrap(),
        interval,
        timezone: fixture.frozen.timezone.parse().unwrap(),
        git_ref: Some(fixture.frozen.git_ref.clone()),
        as_of: Some(DateTime::parse_from_rfc3339(&fixture.frozen.created_at).unwrap()),
        project: None,
        repository_url: None,
        cache_directory: scratch.path().join("cache"),
    };
    let mine = freeze(&run, &options).unwrap();
    let frozen = &fixture.frozen;

    assert_eq!(mine.main_commit, frozen.main_commit);
    assert_eq!(mine.first_commit, frozen.first_commit);
    assert_eq!(mine.first_commit_at, frozen.first_commit_at);
    assert_eq!(mine.first_parent_commits, frozen.first_parent_commits);
    assert_eq!(
        mine.nonmonotonic_commit_dates,
        frozen.nonmonotonic_commit_dates
    );
    assert_eq!(mine.project, frozen.project);
    assert_eq!(mine.repository, frozen.repository);
    assert_eq!(mine.snapshot_policy, frozen.snapshot_policy);
    assert_eq!(mine.snapshots.len(), frozen.snapshots.len());

    let mut differences: Vec<String> = Vec::new();
    for (ours, theirs) in mine.snapshots.iter().zip(&frozen.snapshots) {
        let start = ours.bounds.start();
        assert_eq!(ours.bounds, theirs.bounds);
        assert_eq!(ours.as_of, theirs.as_of);
        assert_eq!(ours.partial, theirs.partial);
        assert_eq!(ours.commit, theirs.commit);
        assert_eq!(ours.committed_at, theirs.committed_at);
        assert_eq!(ours.first_parent_index, theirs.first_parent_index);
        assert_eq!(ours.other_extensions, theirs.other_extensions);
        assert_eq!(ours.excluded_modes, theirs.excluded_modes);

        let our_files: BTreeMap<&str, &str> = ours
            .files
            .iter()
            .map(|entry| (entry.version.as_str(), entry.path.as_str()))
            .collect();
        let their_files: BTreeMap<&str, &str> = theirs
            .files
            .iter()
            .map(|entry| (entry.version.as_str(), entry.path.as_str()))
            .collect();
        differences.extend(
            their_files
                .iter()
                .filter(|(version, _)| !our_files.contains_key(*version))
                .map(|(version, path)| format!("{start}: file {path} ({version}) missing")),
        );
        differences.extend(
            our_files
                .iter()
                .filter(|(version, path)| {
                    !their_files.contains_key(*version) && !profile_matched(path)
                })
                .map(|(version, path)| format!("{start}: file {path} ({version}) unexplained")),
        );

        let our_skipped: BTreeSet<&str> = ours.skipped.iter().map(|s| s.path.as_str()).collect();
        let their_skipped: BTreeSet<&str> =
            theirs.skipped.iter().map(|s| s.path.as_str()).collect();
        differences.extend(
            our_skipped
                .symmetric_difference(&their_skipped)
                .map(|path| format!("{start}: skipped {path} differs")),
        );

        let our_excluded: HashSet<&str> = excluded_paths(ours).into_iter().collect();
        let their_excluded: HashSet<&str> = excluded_paths(theirs).into_iter().collect();
        differences.extend(
            our_excluded
                .difference(&their_excluded)
                .map(|path| format!("{start}: excluded {path} only in the qlty run")),
        );
        differences.extend(
            their_excluded
                .difference(&our_excluded)
                .filter(|path| !profile_matched(path))
                .map(|path| format!("{start}: excluded {path} only in the slopdetect run")),
        );
    }
    assert_eq!(differences, Vec::<String>::new());

    let mut compared = 0;
    for (version, theirs) in &frozen.versions {
        let Some(ours) = mine.versions.get(version) else {
            continue;
        };
        let ours = VersionSummary::new(ours, run.root());
        let theirs = VersionSummary::new(theirs, &fixture.frozen_root);
        if ours != theirs {
            differences.push(format!("{version}: {ours:?} != {theirs:?}"));
        }
        compared += 1;
    }
    assert_eq!(differences, Vec::<String>::new());
    assert_eq!(compared, frozen.versions.len());
    eprintln!(
        "{run_name}: {} snapshots, {} shared versions, {} versions only in the qlty run",
        mine.snapshots.len(),
        compared,
        mine.versions.len() - compared
    );
}

/// The prepared-source facts that must agree for a version in both runs.
#[derive(Debug, PartialEq)]
struct VersionSummary {
    suffix: String,
    bytes: usize,
    source_sha256: String,
    measurement_key: Option<String>,
    source_scope: Option<serde_json::Value>,
    skipped: Option<String>,
    prepared_bytes: Option<usize>,
    excerpts: Option<usize>,
    error: Option<String>,
}

impl VersionSummary {
    fn new(version: &Version, run_root: &Path) -> Self {
        Self {
            suffix: version.suffix.clone(),
            bytes: version.bytes,
            source_sha256: version.source_sha256.clone(),
            measurement_key: version.measurement_key.clone(),
            source_scope: version.source_scope.clone(),
            skipped: version.skipped.clone(),
            prepared_bytes: version.prepared_bytes,
            excerpts: version.excerpts,
            error: normalize_error(version.error.as_deref(), run_root),
        }
    }
}

