#[test]
fn git_attributes_apply_at_each_frozen_commit() {
    let repo = TestRepo::new();
    repo.write("workers/create-backup.ts", SOURCE);
    repo.write("embedded/output.ts", SOURCE);
    repo.write("embedded/authored.ts", "export const authored = 1;\n");
    repo.write(".gitattributes", "embedded/** linguist-generated\n");
    repo.write(
        "embedded/.gitattributes",
        "authored.ts -linguist-generated\n",
    );
    repo.commit("2025-07-02T12:00:00-04:00");
    repo.commit("2025-07-09T12:00:00-04:00");
    repo.write(".gitattributes", "** linguist-generated\n");
    fs::create_dir_all(repo.path().join(".git/info")).unwrap();
    fs::write(
        repo.path().join(".git/info/attributes"),
        "workers/** linguist-generated\n",
    )
    .unwrap();
    let manifest = freeze_weekly(&repo);
    let snapshot = &manifest.snapshots[0];
    assert_eq!(
        file_paths(snapshot),
        ["embedded/authored.ts", "workers/create-backup.ts"]
    );
    assert_eq!(excluded_paths(snapshot), ["embedded/output.ts"]);
    assert_eq!(
        snapshot.source_excluded[0].exclusion,
        json!({
            "policy": "authored-source-002",
            "category": "generated",
            "kind": "git-attribute",
            "matched": "linguist-generated",
        })
    );
    assert_eq!(
        snapshot.source_excluded[0].version.as_deref(),
        Some(
            format!(
                "{}.ts",
                snapshot.source_excluded[0].blob.as_deref().unwrap()
            )
            .as_str()
        )
    );
}

