#[test]
fn prepared_text_is_written_by_measurement_key() {
    let repo = TestRepo::new();
    let manifest = freeze_files(&repo, &[("src/a.ts", SOURCE)]);
    let run = repo.run_dir("weekly");
    let (version, row) = manifest.versions.iter().next().unwrap();
    let key = jev::digest(&json!([".ts", SOURCE])).unwrap();
    assert_eq!(row.measurement_key.as_deref(), Some(key.as_str()));
    assert_eq!(
        row.source.as_deref(),
        Some(format!("sources/{version}").as_str())
    );
    assert_eq!(row.bytes, SOURCE.len());
    assert_eq!(row.prepared_bytes, Some(SOURCE.len()));
    assert_eq!(row.excerpts, Some(1));
    assert_eq!(
        fs::read_to_string(run.prepared_path(&key, ".ts")).unwrap(),
        SOURCE
    );
    assert_eq!(
        fs::read_to_string(run.source_path(version)).unwrap(),
        SOURCE
    );
    assert_eq!(row.source_scope.as_ref().unwrap()["policy"], "whole-file");
}

