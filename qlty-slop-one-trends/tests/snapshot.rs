#[test]
fn workspace_patterns_replace_the_default_rules() {
    let repo = TestRepo::new();
    repo.write(
        ".qlty/qlty.toml",
        "config_version = \"0\"\ntest_patterns = [\"**/*_spec.ts\"]\nexclude_patterns = [\"legacy/**\"]\n",
    );
    let manifest = freeze_files(
        &repo,
        &[
            ("lib/module.test.ts", SOURCE),
            ("lib/thing_spec.ts", SOURCE),
            ("legacy/old.ts", SOURCE),
            ("lib/prisma/client.ts", PRISMA_HEADER),
        ],
    );
    let snapshot = &manifest.snapshots[0];
    assert_eq!(
        file_paths(snapshot),
        ["lib/module.test.ts", "lib/prisma/client.ts"]
    );
    assert_eq!(snapshot.skipped[0].path, "lib/thing_spec.ts");
    assert_eq!(
        snapshot.skipped[0].reason,
        json!({"kind": "glob", "matched": "**/*_spec.ts"})
    );
    assert_eq!(excluded_paths(snapshot), ["legacy/old.ts"]);
    assert_eq!(
        snapshot.source_excluded[0].exclusion,
        json!({
            "policy": "qlty-workspace-exclude-patterns",
            "category": "configured",
            "kind": "glob",
            "matched": "legacy/**",
        })
    );
    assert_eq!(
        manifest.source_exclusion_policy["id"],
        "qlty-workspace-exclude-patterns"
    );
    assert_eq!(
        manifest.source_exclusion_policy["git_attributes"],
        "Not applied; qlty workspace exclude_patterns replace the default source rules."
    );
    assert!(manifest
        .scope
        .contains("replacing the default test-path exclusions"));
}

#[test]
fn workspace_patterns_with_an_extender_are_checked_before_the_default_rules() {
    let repo = TestRepo::new();
    repo.write(
        ".qlty/qlty.toml",
        "config_version = \"0\"\ntest_patterns = [\"...\", \"**/*_spec.ts\"]\nexclude_patterns = [\"...\", \"legacy/**\"]\n",
    );
    repo.write(".gitattributes", "gen/** linguist-generated\n");
    let manifest = freeze_files(
        &repo,
        &[
            ("lib/module.test.ts", SOURCE),
            ("lib/thing_spec.ts", SOURCE),
            ("legacy/old.ts", SOURCE),
            ("docs/prototype.tsx", SOURCE),
            ("gen/output.ts", SOURCE),
            ("lib/prisma/client.ts", PRISMA_HEADER),
            ("src/a.ts", SOURCE),
        ],
    );
    let snapshot = &manifest.snapshots[0];
    assert_eq!(file_paths(snapshot), ["src/a.ts"]);
    assert_eq!(
        snapshot
            .skipped
            .iter()
            .map(|skipped| (skipped.path.as_str(), skipped.reason.clone()))
            .collect::<Vec<_>>(),
        [
            (
                "lib/module.test.ts",
                json!({"kind": "filename", "matched": "test"})
            ),
            (
                "lib/thing_spec.ts",
                json!({"kind": "glob", "matched": "**/*_spec.ts"})
            ),
        ]
    );
    assert_eq!(
        excluded_paths(snapshot),
        [
            "docs/prototype.tsx",
            "legacy/old.ts",
            "gen/output.ts",
            "lib/prisma/client.ts"
        ]
    );
    assert_eq!(
        snapshot
            .source_excluded
            .iter()
            .map(|excluded| (excluded.path.as_str(), excluded.exclusion["policy"].clone()))
            .collect::<Vec<_>>(),
        [
            ("docs/prototype.tsx", json!("authored-source-002")),
            ("legacy/old.ts", json!("qlty-workspace-exclude-patterns")),
            ("gen/output.ts", json!("authored-source-002")),
            ("lib/prisma/client.ts", json!("authored-source-002")),
        ]
    );
    assert_eq!(
        manifest.source_exclusion_policy["id"],
        "authored-source-002"
    );
    assert_eq!(
        manifest.source_exclusion_policy["git_attributes"],
        "Each frozen commit, without checkout/global/system overrides."
    );
    assert!(manifest
        .scope
        .contains("checked before the default test-path exclusions"));
}

