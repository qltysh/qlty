/// The rule set that excluded a file.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
pub enum ExclusionPolicy {
    #[serde(rename = "test-paths-001")]
    TestPaths,
    #[serde(rename = "authored-source-002")]
    AuthoredSource,
    #[serde(rename = "qlty-workspace-test-patterns")]
    QltyWorkspaceTestPatterns,
    #[serde(rename = "qlty-workspace-exclude-patterns")]
    QltyWorkspaceExcludePatterns,
}

impl ExclusionPolicy {
    /// Whether the policy skips test files rather than non-source files.
    pub fn is_test(self) -> bool {
        matches!(self, Self::TestPaths | Self::QltyWorkspaceTestPatterns)
    }
}

/// The root that `matched_path` is relative to.
